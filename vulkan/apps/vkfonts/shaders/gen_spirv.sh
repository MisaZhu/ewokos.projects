#!/bin/sh
# Regenerate vkfonts_spirv.h from shaders/*.vert|frag.
# Requires glslangValidator (brew install glslang) and python3 on the host.
# The fragment shader #includes the verbatim Shadertoy tabs in res/, so
# glslang resolves them relative to shaders/ (GL_GOOGLE_include_directive).
set -e
cd "$(dirname "$0")/.."
glslangValidator -V shaders/vkfonts.vert -o /tmp/vkfonts_vs.spv
glslangValidator -V shaders/vkfonts.frag -o /tmp/vkfonts_fs.spv
python3 - <<'EOF'
import struct

def words(path):
    data = open(path, 'rb').read()
    assert len(data) % 4 == 0
    return list(struct.unpack('<%dI' % (len(data) // 4), data))

vs, fs = words('/tmp/vkfonts_vs.spv'), words('/tmp/vkfonts_fs.spv')

def emit(name, w):
    lines = ['static const uint32_t %s[%d] = {' % (name, len(w))]
    for i in range(0, len(w), 6):
        lines.append('    ' + ', '.join('0x%08x' % x for x in w[i:i+6]) + ',')
    lines.append('};')
    return '\n'.join(lines)

hdr = '''/*
 * vkfonts_spirv.h -- embedded SPIR-V for the vkfonts graphics pipeline.
 * GENERATED by shaders/gen_spirv.sh (glslangValidator); do not edit by hand.
 *
 *   VS: layout(location=0) in vec2 aPos;
 *       void main(){ gl_Position=vec4(aPos,0,1); }   // fullscreen triangle
 *   FS: the VERBATIM Shadertoy "Better Text in Shaders" (kishimisu, 43t3WX)
 *       Common + Image tabs (res/common.glsl, res/image.glsl) wrapped by
 *       shaders/vkfonts.frag: std140 Params UBO (binding 0) supplies
 *       iResolution/iTime/iFrame/iTimeDelta, iChannel0 is binding 1, and
 *       print_char is redefined to emulate the reference's LINEAR+REPEAT
 *       sampler over the CPU interpreter's NEAREST+CLAMP texel fetch.
 *       See shaders/vkfonts.frag for the full adaptation notes.
 */
#ifndef VKFONTS_SPIRV_H
#define VKFONTS_SPIRV_H

#include <stdint.h>

'''
hdr += emit('kFontsVs', vs) + '\n\n' + emit('kFontsFs', fs) + '\n\n#endif\n'
open('vkfonts_spirv.h', 'w').write(hdr)
print('vkfonts_spirv.h: VS %d words, FS %d words' % (len(vs), len(fs)))
EOF