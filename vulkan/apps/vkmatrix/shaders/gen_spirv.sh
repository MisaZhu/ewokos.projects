#!/bin/sh
# Regenerate vkmatrix_spirv.h from shaders/*.vert|frag|comp.
# Requires glslangValidator (brew install glslang) and python3 on the host.
set -e
cd "$(dirname "$0")/.."
glslangValidator -V shaders/matrix.vert -o /tmp/vkmatrix_vs.spv
glslangValidator -V shaders/matrix.frag -o /tmp/vkmatrix_fs.spv
glslangValidator -V shaders/matrix.comp -o /tmp/vkmatrix_cs.spv
python3 - <<'EOF'
import struct

def words(path):
    data = open(path, 'rb').read()
    assert len(data) % 4 == 0
    return list(struct.unpack('<%dI' % (len(data) // 4), data))

vs, fs = words('/tmp/vkmatrix_vs.spv'), words('/tmp/vkmatrix_fs.spv')
cs = words('/tmp/vkmatrix_cs.spv')

def emit(name, w):
    lines = ['static const uint32_t %s[%d] = {' % (name, len(w))]
    for i in range(0, len(w), 6):
        lines.append('    ' + ', '.join('0x%08x' % x for x in w[i:i+6]) + ',')
    lines.append('};')
    return '\n'.join(lines)

hdr = '''/*
 * vkmatrix_spirv.h -- embedded SPIR-V for vkmatrix.
 * GENERATED by shaders/gen_spirv.sh (glslangValidator); do not edit by hand.
 *
 *   VS: layout(location=0) in vec4 aPos; layout(location=1) in vec2 aUV;
 *       layout(location=0) out vec2 vUV;
 *       void main(){ gl_Position=aPos; vUV=aUV; }
 *   FS: layout(set=0,binding=0) uniform sampler2D uTex;
 *       layout(location=0) in vec2 vUV; layout(location=0) out vec4 outColor;
 *       void main(){ outColor=texture(uTex,vUV); }
 *   CS: "Inside the Matrix" (Shadertoy 4t3BWl) per-pixel raymarcher, one
 *       invocation per pixel at NATIVE resolution.  set=0 binding=0 Params
 *       (float[]: time,W,H,ro[3],M[9] column-major), binding=1 OutBuf
 *       (uint[]: W*H packed r|g<<8|b<<16|0xff000000).  local_size_x=64.
 *
 * The graphics pipeline now only draws the ImGui HUD; the rain runs through
 * the compute pipeline on the GPU backend, with matrix.c kept as the CPU
 * fallback when the GPU path declines.
 */
#ifndef VKMATRIX_SPIRV_H
#define VKMATRIX_SPIRV_H

#include <stdint.h>

'''
hdr += emit('kMatrixVs', vs) + '\n\n' + emit('kMatrixFs', fs) + '\n\n'
hdr += emit('kMatrixCs', cs) + '\n\n#endif\n'
open('vkmatrix_spirv.h', 'w').write(hdr)
print('vkmatrix_spirv.h: VS %d words, FS %d words, CS %d words' % (len(vs), len(fs), len(cs)))
EOF