#!/bin/sh
# Regenerate vkolddisp_spirv.h from shaders/*.vert|frag.
# Requires glslangValidator (brew install glslang) and python3 on the host.
# The fragment shader #includes the verbatim Shadertoy tabs in res/, so
# glslang resolves them relative to shaders/ (GL_GOOGLE_include_directive).
set -e
cd "$(dirname "$0")/.."
glslangValidator -V shaders/vkolddisp.vert -o /tmp/vkolddisp_vs.spv
glslangValidator -V shaders/vkolddisp.frag -o /tmp/vkolddisp_fs.spv
python3 - <<'EOF'
import struct

def words(path):
    data = open(path, 'rb').read()
    assert len(data) % 4 == 0
    return list(struct.unpack('<%dI' % (len(data) // 4), data))

vs, fs = words('/tmp/vkolddisp_vs.spv'), words('/tmp/vkolddisp_fs.spv')

def emit(name, w):
    lines = ['static const uint32_t %s[%d] = {' % (name, len(w))]
    for i in range(0, len(w), 6):
        lines.append('    ' + ', '.join('0x%08x' % x for x in w[i:i+6]) + ',')
    lines.append('};')
    return '\n'.join(lines)

hdr = '''/*
 * vkolddisp_spirv.h -- embedded SPIR-V for the vkolddisp graphics pipeline.
 * GENERATED by shaders/gen_spirv.sh (glslangValidator); do not edit by hand.
 *
 *   VS: layout(location=0) in vec2 aPos;
 *       void main(){ gl_Position=vec4(aPos,0,1); }   // fullscreen triangle
 *   FS: Shadertoy "Improved 96-bit 8x12 Font" (JoostAB, lc3BRn).  The font
 *       engine (Common + Buffer A) runs natively in olddisp.c and uploads a
 *       lossless coverage texture; the VERBATIM Buffer B + Image tabs
 *       (res/bufferb.glsl, res/image.glsl) run here as one flattened pass
 *       (same-pixel texelFetch chain, no feedback).  A std140 Params UBO
 *       (binding 0) supplies iResolution/iTime/iFrame/iTimeDelta/iDate and
 *       binding 1 is the coverage texture.  See shaders/vkolddisp.frag.
 */
#ifndef VKOLDDISP_SPIRV_H
#define VKOLDDISP_SPIRV_H

#include <stdint.h>

'''
hdr += emit('kOlddispVs', vs) + '\n\n' + emit('kOlddispFs', fs) + '\n\n#endif\n'
open('vkolddisp_spirv.h', 'w').write(hdr)
print('vkolddisp_spirv.h: VS %d words, FS %d words' % (len(vs), len(fs)))
EOF